import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import type { Plugin } from 'vite'

/**
 * Generated manifests, rewritten on every build (only when changed) and committed, so typecheck runs without a build:
 * - src/film/manifest.ts: a content hash for every file in public/media and public/textures (mediaUrl / texUrl put it on
 *   the URL, so both are cached immutably), plus the hero loop's top tier per codec.
 * - src/reel/manifest.ts: per reel clip (public/media/reel/<id>/{d,m}/NNN.avif, scripts/reel/frames.py) its frame
 *   count, bytes per set and one hash over the set (on every frame URL).
 */
const root = new URL('../', import.meta.url)
const at = (p: string) => new URL(p, root)
const hash = (buf: Buffer) => createHash('sha256').update(buf).digest('hex').slice(0, 10)
/** a /media file's URL with its content hash (scripts/static-hero.ts) */
export const versioned = (f: string) => `/media/${f}${existsSync(at(`public/media/${f}`)) ? `?v=${hash(readFileSync(at(`public/media/${f}`)))}` : ''}`

const files = (dir: string) => (existsSync(at(dir)) ? readdirSync(at(dir)).filter((f) => !f.startsWith('.')).sort() : [])

function filmManifest() {
  const media = files('public/media').filter((f) => statSync(at(`public/media/${f}`)).isFile())
  const tex = files('public/textures')
  const has = (f: string) => media.includes(f)
  return `// Generated by scripts/clip-manifest.ts. Do not edit.
export type Tier = 'm' | 960 | 1280 | 1920 | 2560
export type Codec = 'av1' | 'hevc' | 'h264'

/** the hero loop's top desktop tier per codec: 2560 where that file exists */
export const TOP: Record<Codec, 1920 | 2560> = { av1: ${has('hero-loop_2560.av1.mp4') ? 2560 : 1920}, hevc: ${has('hero-loop_2560.hevc.mp4') ? 2560 : 1920}, h264: 1920 }

/** content hash of every file in public/media (reel frame sets are hashed per set in src/reel/manifest.ts) */
export const MEDIA_V: Record<string, string> = {
${media.map((f) => `  '${f}': '${hash(readFileSync(at(`public/media/${f}`)))}',`).join('\n')}
}

/** content hash of every file in public/textures */
export const TEXTURE_V: Record<string, string> = {
${tex.map((f) => `  '${f}': '${hash(readFileSync(at(`public/textures/${f}`)))}',`).join('\n')}
}
`
}

function reelManifest() {
  const ids = files('public/media/reel')
  const rows = ids.flatMap((id) => {
    const d = files(`public/media/reel/${id}/d`).filter((f) => f.endsWith('.avif'))
    const m = files(`public/media/reel/${id}/m`).filter((f) => f.endsWith('.avif'))
    if (!d.length) return []
    if (d.length !== m.length) throw new Error(`reel manifest: ${id} has ${d.length} desktop and ${m.length} phone frames`)
    const read = (k: string, f: string) => readFileSync(at(`public/media/reel/${id}/${k}/${f}`))
    const bytes = (k: string, l: string[]) => l.reduce((a, f) => a + statSync(at(`public/media/reel/${id}/${k}/${f}`)).size, 0)
    const v = hash(Buffer.from([...d.map((f) => hash(read('d', f))), ...m.map((f) => hash(read('m', f)))].join('')))
    return [`  '${id}': { frames: ${d.length}, d: ${bytes('d', d)}, m: ${bytes('m', m)}, v: '${v}' },`]
  })
  return `// Generated by scripts/clip-manifest.ts from public/media/reel. Do not edit.
export interface ReelClip {
  frames: number
  /** bytes of the desktop and phone sets */
  d: number
  m: number
  v: string
}

export const REEL: Record<string, ReelClip> = {
${rows.join('\n')}
}
`
}

const write = (file: string, next: string) => {
  const url = at(file)
  if (!existsSync(url) || readFileSync(url, 'utf8') !== next) writeFileSync(url, next)
}

export const writeManifests = () => (write('src/film/manifest.ts', filmManifest()), write('src/reel/manifest.ts', reelManifest()))

export function clipManifest(): Plugin {
  return { name: 'clip-manifest', buildStart: writeManifests, configureServer: writeManifests }
}

if (process.argv[1]?.endsWith('clip-manifest.ts')) writeManifests()
